import asyncio, json, time, traceback, hashlib
from pathlib import Path
from playwright.async_api import async_playwright

ROOT=Path(__file__).resolve().parent
CHROME='/workspace/scratch/43b440780c87/playwright-cache/chrome-headless-shell-linux64/chrome-headless-shell'
log={'viewport_desktop':[1440,900],'viewport_mobile':[390,844],'checks':[],'captures':[],'console_errors':[],'external_requests':[]}
start=time.monotonic()
def note(name,passed,detail=None):
    item={'check':name,'pass':passed,'elapsed_s':round(time.monotonic()-start,3)}
    if detail is not None:item['detail']=detail
    log['checks'].append(item)
    print(json.dumps(item),flush=True)
    assert passed, name
async def capture(page,name):
    t0=time.monotonic()-start
    await page.screenshot(path=str(ROOT/(name+'.png')))
    log['captures'].append({'file':name+'.png','capture_start_s':round(t0,3),'capture_end_s':round(time.monotonic()-start,3)})
async def completed(page):
    await page.locator('.answer').last.wait_for()
    await page.wait_for_function("document.querySelectorAll('.answer')[document.querySelectorAll('.answer').length-1]?.dataset.status === 'complete'",timeout=25000)
async def choose(page,mode):
    await page.locator('#demo-open-top').click()
    await page.locator('#next-response').select_option(mode)
    await page.locator('#demo-done').click()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path=CHROME,args=['--no-sandbox'])
        context=await b.new_context(viewport={'width':1440,'height':900},device_scale_factor=1,color_scheme='light')
        page=await context.new_page()
        page.on('pageerror',lambda e:log['console_errors'].append(str(e)))
        page.on('request',lambda r:log['external_requests'].append(r.url) if not r.url.startswith('http://127.0.0.1:8844/') else None)
        await page.goto('http://127.0.0.1:8844/app/')
        await capture(page,'01-desktop-empty')
        note('Empty composer disabled until text',await page.locator('#send').is_disabled())
        await page.locator('[data-prompt]').first.click()
        await capture(page,'02-pending')
        note('Immediate stop action visible',await page.locator('#stop').is_visible())
        await page.wait_for_timeout(1250)
        await capture(page,'03-streaming')
        n=await page.locator('.answer-content').inner_text()
        note('Answer unfolds asynchronously',len(n)>20 and await page.locator('#stop').is_visible(),{'visible_characters':len(n)})
        await completed(page)
        note('First question completes with three source controls',await page.locator('.source-chip').count()==3)
        await page.locator('#reader').evaluate('(el)=>el.scrollTop=0')
        await capture(page,'04-desktop-answer-top')
        await page.locator('.source-chip').first.click()
        await page.wait_for_timeout(150)
        note('Desktop source is non-modal and composer remains usable',await page.locator('#source-dialog').evaluate("el=>el.open&&!el.matches(':modal')"))
        await page.locator('#question').fill('What would a pilot look like?')
        await capture(page,'05-desktop-source')
        await page.locator('#source-close').click()
        note('Source returns focus to citation',await page.evaluate("document.activeElement.classList.contains('source-chip')"))
        note('Source preserves follow-up draft',await page.locator('#question').input_value()=='What would a pilot look like?')
        await choose(page,'long')
        await page.locator('#send').click()
        await page.wait_for_timeout(2200)
        await page.locator('#reader').evaluate('(el)=>el.scrollTop=0')
        before=await page.locator('#reader').evaluate('el=>el.scrollTop')
        await page.wait_for_timeout(1400)
        after=await page.locator('#reader').evaluate('el=>el.scrollTop')
        note('Streaming preserves earlier reading position',abs(before-after)<3,{'before':before,'after':after})
        note('Latest response affordance appears while reading earlier text',await page.locator('#latest').is_visible())
        await capture(page,'06-reading-while-streaming')
        await page.locator('#question').fill('Keep this next question as a draft')
        await page.locator('#stop').click()
        stopped=await page.locator('.answer-content').last.inner_text()
        await page.wait_for_timeout(750)
        note('Stop freezes partial answer',stopped==await page.locator('.answer-content').last.inner_text())
        note('Stop retains newly typed draft',await page.locator('#question').input_value()=='Keep this next question as a draft')
        await page.locator('#latest').click()
        await capture(page,'07-stopped')
        await page.locator('.answer-state button').last.click()
        await completed(page)
        note('Retry replaces stopped answer without duplicate question',await page.locator('.message.user').count()==2)
        await choose(page,'failure')
        await page.locator('#question').fill('What assumptions should we revisit?')
        await page.locator('#send').click()
        await page.wait_for_selector('.answer[data-status=error]')
        await capture(page,'08-failure')
        users=await page.locator('.message.user').count()
        await page.locator('.answer-state button').last.click()
        await completed(page)
        note('Simulated failure recovers without duplicate question',await page.locator('.message.user').count()==users)
        await page.locator('#question').fill('A draft worth keeping\nWith a second line')
        await page.locator('#file-picker').set_input_files([{'name':'route-notes.txt','mimeType':'text/plain','buffer':b'never read by the application'}])
        await page.wait_for_timeout(250)
        note('Filename chip displayed',await page.locator('.attachment-chip').inner_text()=='route-notes.txt')
        await page.reload()
        note('Threads persist over HTTP reload',await page.locator('.message.user').count()==3)
        note('Multiline draft persists over reload',await page.locator('#question').input_value()=='A draft worth keeping\nWith a second line')
        note('Filename persists over reload',await page.locator('.attachment-chip').count()==1)
        await page.locator('#theme').click()
        await page.locator('#reader').evaluate('(el)=>el.scrollTop=0')
        await capture(page,'09-desktop-dark')
        note('Desktop has no horizontal page overflow',await page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        await context.close()

        context=await b.new_context(viewport={'width':390,'height':844},device_scale_factor=1,color_scheme='light',has_touch=True)
        page=await context.new_page()
        page.on('pageerror',lambda e:log['console_errors'].append(str(e)))
        page.on('request',lambda r:log['external_requests'].append(r.url) if not r.url.startswith('http://127.0.0.1:8844/') else None)
        await page.goto('http://127.0.0.1:8844/app/')
        await capture(page,'10-mobile-empty')
        note('Mobile has no horizontal page overflow',await page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
        await page.locator('#nav-open').click()
        await capture(page,'11-mobile-navigation')
        note('Mobile history uses native modal',await page.locator('#nav-dialog').evaluate("el=>el.matches(':modal')"))
        await page.locator('[data-example=heat]').click()
        note('Opening a sample closes navigation',not await page.locator('#nav-dialog').evaluate('el=>el.open'))
        await capture(page,'12-mobile-answer')
        await page.locator('.source-chip').first.click()
        await capture(page,'13-mobile-source')
        note('Mobile source uses modal semantics',await page.locator('#source-dialog').evaluate("el=>el.matches(':modal')"))
        await page.keyboard.press('Escape')
        note('Escape closes source and restores citation focus',not await page.locator('#source-dialog').evaluate('el=>el.open') and await page.evaluate("document.activeElement.classList.contains('source-chip')"))
        await page.locator('#question').fill('Compare these observations\nAcross two places\nAnd several times of day\nKeep assumptions visible\nThen suggest a pilot')
        height=await page.locator('#question').evaluate('el=>el.clientHeight')
        note('Composer grows and is bounded on mobile',90<=height<=125,{'height':height})
        await capture(page,'14-mobile-multiline')
        await page.locator('#nav-open').click()
        await page.locator('#theme').click()
        await page.locator('#nav-close').click()
        await capture(page,'15-mobile-dark')
        await page.reload()
        note('Appearance persists',await page.locator('html').get_attribute('data-theme')=='dark')
        await page.emulate_media(reduced_motion='reduce')
        await choose(page,'slow')
        await page.locator('#question').fill('A slow question')
        await page.locator('#question').press('Enter')
        note('Keyboard Enter submits on mobile viewport',await page.locator('#stop').is_visible())
        note('Reduced motion removes decorative pulse',await page.locator('.pending-dot').evaluate("el=>getComputedStyle(el).animationName")=='none')
        await page.locator('#stop').click()
        await page.locator('#question').fill('First line')
        await page.locator('#question').press('Shift+Enter')
        note('Shift Enter inserts a newline',await page.locator('#question').input_value()=='First line\n')
        note('No unhandled JavaScript errors',not log['console_errors'],log['console_errors'])
        note('Application makes no external requests',not log['external_requests'],log['external_requests'])
        log['browser']=b.version
        await context.close();await b.close()

try:asyncio.run(main())
except Exception as e:
    log['failure']=str(e);log['traceback']=traceback.format_exc();print(log['traceback'])
